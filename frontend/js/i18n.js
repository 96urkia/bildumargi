let IDIOMA = "es";

function fijarIdioma(codigo) {
  IDIOMA = TEXTOS[codigo] ? codigo : "es";
  document.documentElement.lang = IDIOMA;
}

function t(clave, sustituciones) {
  let texto = (TEXTOS[IDIOMA] && TEXTOS[IDIOMA][clave]) || TEXTOS.es[clave] || clave;
  if (sustituciones) {
    for (const [k, v] of Object.entries(sustituciones)) {
      texto = texto.replaceAll(`{${k}}`, v);
    }
  }
  return texto;
}

