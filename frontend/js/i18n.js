function traducirEtiqueta(texto) {
  if (!texto || IDIOMA === "es") return texto;
  const tabla = ETIQUETAS_SERVIDOR[IDIOMA];
  if (tabla && tabla[texto]) return tabla[texto];
  const secc = NOMBRES_SECCION[IDIOMA];
  if (!secc) return texto;
  if (secc[texto]) return secc[texto];
  let m = /^(I )?(159\.9|\d) - (.+)$/.exec(texto);              // «9 - Historia / Geografía», «I 5 - Ciencias Puras»
  if (m) return `${m[1] || ""}${m[2]} - ${secc[m[3]] || m[3]}`;
  m = /^(\S+) (\(Infantil\))$/.exec(texto);               // «I1 (Infantil)»
  if (m) return `${m[1]} ${secc[m[2]] || m[2]}`;
  return texto;
}
